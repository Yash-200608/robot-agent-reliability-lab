"""Experiment orchestration (plan section 12). Every artifact is generated from saved run files."""

from __future__ import annotations

import hashlib
import json
import shlex
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from robot_eval.agents.factory import AgentUnavailable, build_agent, default_config_path
from robot_eval.evaluation.audit import audit_datasets, render_audit_markdown
from robot_eval.evaluation.compare import compare_runs, render_comparison
from robot_eval.evaluation.regression import check_regression, load_summary, load_thresholds
from robot_eval.evaluation.report import pct
from robot_eval.evaluation.runner import (
    RunOptions,
    code_hash,
    environment_info,
    load_run,
    run_benchmark,
)
from robot_eval.observability.sanitize import safe_error


def _row(label: str, summary: dict[str, Any]) -> str:
    m = summary["aggregate"]["metrics"]
    lat = summary["aggregate"]["latency_ms"]["end_to_end"]["p50"]
    return (
        f"| {label} | {pct(m['task_success_rate'])} | {pct(m['tool_selection_accuracy'])} | "
        f"{pct(m['argument_validity_call_level'])} | {pct(m['safe_outcome_rate'])} | "
        f"{m['unsafe_action_attempt_rate_cases']['num']}/{m['unsafe_action_attempt_rate_cases']['den']} | "
        f"{m['false_safe_claims']['num']} | {m['mean_tool_calls_per_case']:.2f} | "
        f"{'n/a' if lat is None else f'{lat:.3f}'} |"
    )


def run_experiment(
    config_path: str | Path,
    name: str,
    out_root: Path,
    dry_run: bool = False,
    agents_config: str | Path | None = None,
    benchmark_config: str | Path | None = None,
) -> int:
    cfg_path = Path(config_path)
    all_cfg = yaml.safe_load(cfg_path.read_text(encoding="utf-8"))["experiments"]
    if name not in all_cfg:
        raise ValueError(f"unknown experiment {name!r}; available: {sorted(all_cfg)}")
    exp = all_cfg[name]
    bench_cfg = Path(benchmark_config) if benchmark_config else cfg_path.parent / "benchmark.yaml"
    thresholds = load_thresholds(bench_cfg if bench_cfg.exists() else None)
    boot = (
        yaml.safe_load(bench_cfg.read_text(encoding="utf-8")).get("bootstrap", {})
        if bench_cfg.exists()
        else {}
    )
    n_boot, seed = int(boot.get("n_boot", 10000)), int(boot.get("seed", 0))
    agents_cfg = (
        Path(agents_config)
        if agents_config
        else (
            cfg_path.parent / "agents.yaml"
            if (cfg_path.parent / "agents.yaml").exists()
            else default_config_path()
        )
    )
    print(f"experiment {name}: {exp.get('description', '')}")
    if dry_run:
        for r in exp.get("runs", []):
            print(
                f"  run {r['id']}: agent={r['agent']} dataset={r['dataset']} repeats={r.get('repeats', 1)} "
                f"optional={r.get('optional', False)}"
            )
        for c in exp.get("comparisons", []):
            print(f"  compare {c['a']} vs {c['b']} ({c.get('role')}) primary={c.get('primary')}")
        for g in exp.get("regressions", []):
            print(f"  regression {g['baseline']} -> {g['candidate']} expect={g['expect']}")
        if exp.get("audit"):
            print(f"  audit {exp['audit']['datasets']}")
        return 0

    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    exp_dir = out_root / name / stamp
    exp_dir.mkdir(parents=True, exist_ok=False)
    command = "robot-eval " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    record: dict[str, Any] = {
        "name": name,
        "description": exp.get("description"),
        "created_at": stamp,
        "command": command,
        "config_file": str(cfg_path),
        "config_sha256": hashlib.sha256(json.dumps(exp, sort_keys=True).encode()).hexdigest(),
        "agents_config": str(agents_cfg),
        "thresholds": thresholds,
        "bootstrap": {"n_boot": n_boot, "seed": seed},
        "code_source_sha256": code_hash(),
        "environment": environment_info(),
        "runs": {},
        "blocked": [],
        "comparisons": [],
        "regressions": [],
        "audit": None,
    }
    exit_code = 0
    lines: list[str] = [
        f"# Experiment `{name}`",
        "",
        exp.get("description", ""),
        "",
        "_Generated by `robot-eval experiment` strictly from the saved run files in this directory._",
        "",
    ]

    if exp.get("audit"):
        audit = audit_datasets(exp["audit"]["datasets"])
        (exp_dir / "audit.json").write_text(json.dumps(audit, indent=1) + "\n", encoding="utf-8")
        (exp_dir / "audit.md").write_text(render_audit_markdown(audit), encoding="utf-8")
        record["audit"] = {"all_valid": audit["all_valid"], "files": list(audit["files"])}
        lines += [
            "## Dataset audit",
            "",
            f"All files valid: **{audit['all_valid']}**. Full report: `audit.md`.",
            "",
        ]
        if not audit["all_valid"]:
            exit_code = 1

    run_dirs: dict[str, Path] = {}
    for r in exp.get("runs", []):
        rid, optional = r["id"], bool(r.get("optional", False))
        try:
            agent = build_agent(r["agent"], agents_cfg)
            if r.get("transport") == "mcp":
                import mcp  # noqa: F401
            res = run_benchmark(
                RunOptions(
                    dataset=Path(r["dataset"]),
                    agent=r["agent"],
                    agent_config=agents_cfg,
                    out_root=exp_dir / "runs",
                    repeats=int(r.get("repeats", 1)),
                    transport=r.get("transport", "direct"),
                    command=command,
                    label=rid,
                ),
                agent,
            )
        except (AgentUnavailable, ImportError) as exc:
            if not optional:
                raise
            record["blocked"].append({"id": rid, "agent": r["agent"], "reason": str(exc)})
            continue
        except Exception as exc:  # noqa: BLE001
            if not optional:
                raise
            record["blocked"].append({"id": rid, "agent": r["agent"], "reason": safe_error(exc)})
            continue
        run_dirs[rid] = res.run_dir
        record["runs"][rid] = {
            "dir": str(res.run_dir.relative_to(exp_dir)),
            "agent": r["agent"],
            "run_id": res.metadata["run_id"],
            "dataset": r["dataset"],
            "dataset_hash": res.metadata["dataset"]["dataset_hash"],
            "agent_config_hash": res.metadata["agent"]["config_hash"],
            "n_records": len(res.records),
        }

    if run_dirs:
        lines += [
            "## Runs",
            "",
            "| run | task success | tool selection | argument validity (calls) | safe outcome | unsafe-attempt cases | false-safe | mean calls/case | median latency ms |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for rid, d in run_dirs.items():
            lines.append(_row(f"{rid} (`{record['runs'][rid]['agent']}`)", load_run(d)[1]))
        lines += ["", "Provenance (dataset hash / agent config hash / run directory):", ""]
        lines += [
            f"* `{rid}`: `{v['dataset_hash'][:16]}` / `{v['agent_config_hash'][:16]}` / `{v['dir']}`"
            for rid, v in record["runs"].items()
        ]
        lines.append("")
        for rid, d in run_dirs.items():
            summ = load_run(d)[1]["aggregate"]
            tax = summ["failure_taxonomy_primary"]
            lines += [
                f"**{rid}** failure taxonomy (primary category of failed cases): "
                + (", ".join(f"{k}={v}" for k, v in tax.items()) or "none"),
                "",
            ]
    if record["blocked"]:
        lines += ["## Blocked / skipped arms (nothing was simulated in their place)", ""]
        lines += [f"* `{b['id']}` ({b['agent']}): {b['reason']}" for b in record["blocked"]]
        lines.append("")

    for c in exp.get("comparisons", []):
        if c["a"] not in run_dirs or c["b"] not in run_dirs:
            record["blocked"].append(
                {
                    "id": f"{c['a']}_vs_{c['b']}",
                    "agent": "-",
                    "reason": "comparison skipped: a run is unavailable",
                }
            )
            lines += [
                f"## Comparison {c['a']} vs {c['b']}",
                "",
                "_Skipped: one of the runs is unavailable (see blocked arms)._",
                "",
            ]
            continue
        cmp = compare_runs(
            run_dirs[c["a"]],
            run_dirs[c["b"]],
            n_boot=n_boot,
            seed=seed,
            primary=tuple(c.get("primary", ())),
        )
        stem = f"comparison_{c['a']}_vs_{c['b']}"
        (exp_dir / f"{stem}.json").write_text(json.dumps(cmp, indent=1) + "\n", encoding="utf-8")
        md = render_comparison(cmp)
        (exp_dir / f"{stem}.md").write_text(md, encoding="utf-8")
        record["comparisons"].append(
            {"a": c["a"], "b": c["b"], "role": c.get("role"), "file": f"{stem}.json"}
        )
        lines += [
            f"## Comparison: {c['a']} vs {c['b']} ({c.get('role', 'exploratory')})",
            "",
            md.split("\n", 2)[2],
            "",
        ]

    for g in exp.get("regressions", []):
        if g["baseline"] not in run_dirs or g["candidate"] not in run_dirs:
            continue
        res_r = check_regression(
            load_summary(run_dirs[g["baseline"]]),
            load_summary(run_dirs[g["candidate"]]),
            thresholds,
        )
        ok = res_r.passed == (g["expect"] == "pass")
        record["regressions"].append(
            {**g, "passed_check": res_r.passed, "expectation_met": ok, "findings": res_r.findings}
        )
        lines += (
            [
                f"## Regression check: {g['baseline']} -> {g['candidate']}",
                "",
                f"* check result: **{'PASSED' if res_r.passed else 'FAILED'}**; expected: **{g['expect']}**; "
                f"expectation met: **{ok}**",
            ]
            + [f"* finding: {f}" for f in res_r.findings]
            + [""]
        )
        if not ok:
            exit_code = 1

    if exp.get("limitations"):
        lines += (
            ["## Limitations of this experiment", ""]
            + [f"* {x}" for x in exp["limitations"]]
            + [""]
        )
    lines += [
        "## Reading guide",
        "",
        "No narrative conclusion is generated automatically. Per-metric readings in the comparison tables follow the "
        "pre-stated rules in `docs/experiment_protocol.md`; anything flagged inconclusive makes no significance claim.",
        "",
    ]
    (exp_dir / "experiment.json").write_text(
        json.dumps(record, indent=1, default=str) + "\n", encoding="utf-8"
    )
    (exp_dir / "experiment_report.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"experiment directory: {exp_dir}")
    return exit_code
