"""Generates docs/tools.md from the live registry and real simulator outputs (so it cannot drift:
tests/unit/test_docs.py fails if the committed file differs from this output)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from robot_eval.simulator.sim import Simulator
from robot_eval.simulator.world import FaultSpec, load_worlds
from robot_eval.tools.registry import TOOL_REGISTRY

EXAMPLES: list[tuple[str, str, dict[str, Any]]] = [
    ("get_workcell_state", "valid", {}),
    (
        "check_reachability",
        "valid (exactly on the 2.5 m reach limit: inclusive)",
        {"x": 1.5, "y": 2.0},
    ),
    ("check_reachability", "valid result: not reachable", {"x": 2.0, "y": 2.0}),
    ("check_collision", "valid (touching obstacle o1 counts as collision)", {"x": 1.5, "y": 1.3}),
    (
        "check_clearance",
        "valid (clearance exactly equals the 0.1 m margin: acceptable)",
        {"x": 1.56, "y": 1.38},
    ),
    (
        "validate_joint_limits",
        "valid (limits are inclusive)",
        {"joints": {"shoulder": 90, "elbow": 150}},
    ),
    ("plan_path", "valid (detour needed in cell_c; shown in a separate world below)", {}),
    (
        "validate_path",
        "valid result: path invalid",
        {"waypoints": [{"x": 1.0, "y": -0.5}, {"x": 1.0, "y": 1.6}]},
    ),
    (
        "estimate_operation_feasibility",
        "valid result: weld infeasible (stricter margin)",
        {"operation": "weld_point", "x": 1.56, "y": 1.38},
    ),
    ("move_end_effector", "valid (state-changing)", {"x": 1.0, "y": 0.0}),
    ("move_end_effector", "tool error: collision, pose unchanged", {"x": 1.2, "y": 0.9}),
    ("move_end_effector", "tool error: safe target but unsafe path", {"x": 1.0, "y": 1.6}),
    ("check_reachability", "invalid argument: string instead of number", {"x": "1.0", "y": 0.0}),
    ("check_reachability", "invalid argument: unknown field", {"x": 1.0, "y": 0.0, "z": 1.0}),
    (
        "check_collision",
        "invalid argument: out of schema range (|v| <= 1000 m)",
        {"x": 5000.0, "y": 0.0},
    ),
    ("validate_joint_limits", "invalid argument: unknown joint", {"joints": {"tentacle": 5}}),
    ("inspect_tool_schema", "valid", {"tool_name": "check_clearance"}),
    ("get_simulation_diagnostics", "valid (most recent logged operation)", {}),
]


def _fmt(d: Any) -> str:
    return json.dumps(d, indent=None, separators=(", ", ": "), allow_nan=False)


def render(datasets_dir: str | Path) -> str:
    worlds = load_worlds(Path(datasets_dir) / "worlds.json")
    sim = Simulator(worlds["cell_a"])
    out = [
        "# Simulated tools",
        "",
        "_Generated by `robot_eval.tools.docgen` from the live registry and real simulator output; "
        "`tests/unit/test_docs.py` fails if this file is stale._",
        "",
        "All tools are local, deterministic and simulation-only (no network, no hardware). Units: metres and "
        "degrees. Coordinates: x right, y up, origin of the workcell frame. Inputs are strictly validated: unknown "
        "fields, strings where numbers are expected, booleans, NaN/inf and |value| > 1000 are rejected with "
        "`INVALID_ARGUMENT` and **no state change**.",
        "",
        "## Tool list",
        "",
        "| tool | state-changing | description |",
        "|---|---|---|",
    ]
    for s in TOOL_REGISTRY.values():
        out.append(f"| `{s.name}` | {'**yes**' if s.mutating else 'no'} | {s.description} |")
    out += [
        "",
        "## Semantics fixed by the simulator (and mirrored independently by the exact-arithmetic oracle)",
        "",
        "* Obstacles are closed discs; **touching = collision** (clearance <= 0).",
        "* A required clearance margin is met when clearance >= margin (**equality is safe**).",
        "* Reach band, workspace and joint limits are closed intervals (equality is inside).",
        "* Violation precedence for the *primary* error code: OUT_OF_BOUNDS > TARGET_UNREACHABLE > COLLISION > "
        "INSUFFICIENT_CLEARANCE > PATH_UNREACHABLE > PATH_COLLISION > PATH_CLEARANCE. All violated codes are "
        "listed in `data.violation_codes`.",
        "* Only `move_end_effector` mutates the world (end-effector pose), and only after every check passes. "
        "Failed or rejected calls leave the pose unchanged.",
        "",
        "## Examples (world `cell_a`; output produced by the simulator)",
        "",
        "`cell_a`: base (0,0), reach 0.3-2.5 m, margin 0.1 m, obstacle o1 = centre (1.2, 0.9) radius 0.5, home (1.0, -0.5).",
        "",
    ]
    for tool, label, args in EXAMPLES:
        if tool == "plan_path":
            continue
        res = sim.call(tool, args)
        out += [
            f"### `{tool}` - {label}",
            "",
            "```json",
            f"// arguments: {_fmt(args)}",
            json.dumps(res.model_dump(mode="json"), indent=1, allow_nan=False),
            "```",
            "",
        ]
    cc = Simulator(worlds["cell_c"])
    pargs = {"start": {"x": -1.0, "y": 0.0}, "goal": {"x": 1.0, "y": 0.0}}
    out += [
        "### `plan_path` - valid detour (world `cell_c`: obstacle of radius 0.8 at the origin blocks the straight line)",
        "",
        "```json",
        f"// arguments: {_fmt(pargs)}",
        json.dumps(cc.call("plan_path", pargs).model_dump(mode="json"), indent=1, allow_nan=False),
        "```",
        "",
    ]
    walled = Simulator(worlds["cell_walled"])
    wargs = {"start": {"x": -1.0, "y": -1.5}, "goal": {"x": 1.0, "y": 1.5}}
    out += [
        "### `plan_path` - tool error (world `cell_walled`: a wall of obstacles spans the whole workspace)",
        "",
        "```json",
        f"// arguments: {_fmt(wargs)}",
        json.dumps(
            walled.call("plan_path", wargs).model_dump(mode="json"), indent=1, allow_nan=False
        ),
        "```",
        "",
    ]
    fsim = Simulator(
        worlds["cell_a"], [FaultSpec(tool="check_collision", kind="timeout", fail_first_n=1)]
    )
    fargs = {"x": 0.0, "y": 0.5}
    out += [
        "### Injected fault (benchmark fault-injection cases): first `check_collision` call times out",
        "",
        "```json",
        f"// arguments: {_fmt(fargs)} (called twice)",
        json.dumps(
            fsim.call("check_collision", fargs).model_dump(mode="json"), indent=1, allow_nan=False
        ),
        json.dumps(
            fsim.call("check_collision", fargs).model_dump(mode="json"), indent=1, allow_nan=False
        ),
        "```",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":  # pragma: no cover
    from robot_eval.agents.factory import repo_root

    root = repo_root()
    (root / "docs" / "tools.md").write_text(
        render(root / "datasets"), encoding="utf-8", newline="\n"
    )
    print(f"wrote {root / 'docs' / 'tools.md'}")
